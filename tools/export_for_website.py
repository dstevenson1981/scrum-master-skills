#!/usr/bin/env python3
"""Build the agile36.com skill files and page data from library.json.

    python3 tools/export_for_website.py /path/to/agile36-website

Writes:
  public/skills/scrum-master/<name>/SKILL.md      one file: SKILL.md with references folded in
  public/skills/scrum-master/<name>/<name>.zip     full skill folder, for the Claude app
  public/skills/scrum-master/<name>/<name>.prompt.md  GitHub Copilot prompt file
  app/lib/academy/scrum-master-skills.ts           data for /academy/scrum-master-skills

Only skills stored in this repo (Agile36's own, CC BY 4.0, and MIT copies) get
files. Others are listed with a link to their author's repository.
"""
import json
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(KIT / "tools"))
import export_skill  # noqa: E402
import install_library  # noqa: E402


def single_file(staged: Path) -> str:
    text = (staged / "SKILL.md").read_text(encoding="utf-8")
    m = re.match(r"^(---\n.*?\n---\n)", text, re.S)
    front = m.group(1)
    _, body = export_skill.parse_skill(staged)
    full = export_skill.build_body(body, export_skill.collect_refs(staged), True)
    note = ""
    if (staged / "scripts").is_dir():
        note = ("\n> This single-file version leaves out the skill's Python tools. "
                "Download the .zip for the full skill.\n")
    return f"{front}{note}\n{full}"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    site = Path(sys.argv[1]).expanduser().resolve()
    if not (site / "app").is_dir() or not (site / "public").is_dir():
        sys.exit(f"{site} doesn't look like the agile36 website (no app/ or public/)")
    lib = json.loads((KIT / "library.json").read_text(encoding="utf-8"))
    out_root = site / "public/skills/scrum-master"
    if out_root.exists():
        shutil.rmtree(out_root)
    out_root.mkdir(parents=True)

    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for s in lib["skills"]:
            name = s["install_name"]
            local = "local" in s["source"]
            row = {
                "slug": name, "category": s["category"], "job": s["job"], "level": s["level"],
                "needs": s["needs"], "tryPrompt": s["try_prompt"], "optional": bool(s.get("optional")),
                "author": s.get("author") or (s["license"].split("(")[1].split(")")[0] if "(" in s["license"]
                                              else s["source"].get("repo", "")),
                "license": s["license"].split(",")[0],
                "sourceUrl": (f"https://github.com/{lib['kit_repo']}/tree/main/{s['source']['local']}" if local
                              else f"https://github.com/{s['source']['repo']}/tree/{s['source']['ref']}/{s['source']['path']}"),
                "hasFiles": local,
                "hasTools": False,
            }
            if local:
                staged = install_library.stage(s, Path(tmp) / "stage")
                row["hasTools"] = (staged / "scripts").is_dir()
                d = out_root / name
                d.mkdir(parents=True)
                (d / "SKILL.md").write_text(single_file(staged), encoding="utf-8")
                with zipfile.ZipFile(d / f"{name}.zip", "w", zipfile.ZIP_DEFLATED) as zf:
                    for p in sorted(staged.rglob("*")):
                        if p.is_file():
                            zf.write(p, Path(name) / p.relative_to(staged))
                meta, body = export_skill.parse_skill(staged)
                full = export_skill.build_body(body, export_skill.collect_refs(staged), True)
                desc = meta["description"].replace('"', "'")
                (d / f"{name}.prompt.md").write_text(f'---\ndescription: "{desc}"\n---\n\n{full}', encoding="utf-8")
            rows.append(row)

    ts = ("// Generated by scrum-master-skills/tools/export_for_website.py. Do not edit by hand;\n"
          "// edit library.json in github.com/" + lib["kit_repo"] + " and re-run the script.\n\n"
          "export type ScrumSkill = {\n  slug: string;\n  category: string;\n  job: string;\n"
          "  level: 'beginner' | 'intermediate' | 'advanced';\n  needs: string;\n  tryPrompt: string;\n"
          "  optional: boolean;\n  author: string;\n  license: string;\n  sourceUrl: string;\n"
          "  hasFiles: boolean;\n  hasTools: boolean;\n};\n\n"
          f"export const SCRUM_SKILLS_REPO = {json.dumps('https://github.com/' + lib['kit_repo'])};\n\n"
          "export const SCRUM_SKILLS_INSTALL =\n  "
          + json.dumps(f"curl -fsSL https://raw.githubusercontent.com/{lib['kit_repo']}/main/tools/install_library.py | python3 -")
          + ";\n\nexport const SCRUM_SKILLS: ScrumSkill[] = "
          + json.dumps(rows, indent=2, ensure_ascii=False) + ";\n")
    ts_path = site / "app/lib/academy/scrum-master-skills.ts"
    ts_path.write_text(ts, encoding="utf-8")
    n_files = sum(r["hasFiles"] for r in rows)
    print(f"{len(rows)} skills; files for {n_files} -> {out_root}")
    print(f"data -> {ts_path}")


if __name__ == "__main__":
    main()
